/* 通用：按分段线性插值取值 */
export function lerpStops(stops, x) {
  if (x <= stops[0][0]) return stops[0][1]
  for (let i = 1; i < stops.length; i++) {
    if (x <= stops[i][0]) {
      const [x0, v0] = stops[i - 1]
      const [x1, v1] = stops[i]
      const k = (x - x0) / (x1 - x0)
      if (Array.isArray(v0)) return v0.map((v, j) => v + (v1[j] - v) * k)
      return v0 + (v1 - v0) * k
    }
  }
  return stops[stops.length - 1][1]
}
